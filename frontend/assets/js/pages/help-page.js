const renderToc = () => sections
  .map(([id, title]) => `<a href="#${id}">${title}</a>`)
  .join('');

const renderSection = ([id, title, paragraphs]) => `
  <section class="card help-section" id="${id}" tabindex="-1">
    <h2>${title}</h2>
    ${paragraphs.map((text) => `<p>${text}</p>`).join('')}
  </section>
`;

document.body.innerHTML = buildLayout('help', `
  <main class="help-main">
    ${buildPageHeader({
      title: 'Справка SubHub',
    })}

    <div class="help-layout">
      <aside class="card help-toc" aria-label="Оглавление справки">${renderToc()}</aside>
      <div class="help-content">${sections.map(renderSection).join('')}</div>
    </div>
  </main>
`);

initLayoutUI();

const focusHashSection = () => {
  document.getElementById(window.location.hash.slice(1))?.scrollIntoView({ block: 'start' });
};

window.addEventListener('hashchange', focusHashSection);
window.setTimeout(focusHashSection, 50);
